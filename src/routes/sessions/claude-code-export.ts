/**
 * Claude Code prompt export endpoint.
 *
 * Takes the interview results (facts, hypotheses, PRD, spec) and generates
 * a structured prompt that Claude Code can use to implement the feature.
 * Includes default non-functional requirements.
 */

import { Hono } from "hono";
import { ANALYSIS_TYPE } from "../../constants.ts";
import { db } from "../../db/index.ts";
import { saveAnalysisResult } from "../../helpers/analysis-store.ts";
import { formatNFRsAsMarkdown, getNFRDefaults } from "../../helpers/nfr-defaults.ts";
import { getOwnedSession, isResponse } from "../../helpers/session-ownership.ts";
import type { AppEnv, Session } from "../../types.ts";

export const claudeCodeExportRoutes = new Hono<AppEnv>();

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

interface FactItem {
  type: string;
  content: string;
  severity: string;
}

interface PRDFeature {
  name: string;
  description: string;
  priority: string;
  acceptanceCriteria?: string[];
  edgeCases?: string[];
}

interface PRDData {
  problemDefinition?: string;
  targetUser?: string;
  jobsToBeDone?: string[];
  coreFeatures?: PRDFeature[];
  nonGoals?: string[];
  qualityRequirements?: Record<string, { description?: string; criteria?: string[] }>;
}

/**
 * Detect context hints from interview data to adjust NFR defaults.
 */
function detectNFRContext(
  facts: FactItem[],
  prd: PRDData,
): {
  isInternalTool: boolean;
  handlesPersonalData: boolean;
  hasExternalUsers: boolean;
} {
  const allText = [
    ...(facts || []).map((f) => f.content),
    prd.problemDefinition || "",
    prd.targetUser || "",
    ...(prd.jobsToBeDone || []),
  ]
    .join(" ")
    .toLowerCase();

  return {
    isInternalTool: /社内|内部|チーム|internal|team only/.test(allText),
    handlesPersonalData: /個人情報|personal data|メールアドレス|email|名前|氏名|住所|電話/.test(allText),
    hasExternalUsers: /顧客|ユーザー|customer|end.?user|外部|public/.test(allText),
  };
}

/**
 * Build the Claude Code prompt from analysis results.
 */
function buildClaudeCodePrompt(
  theme: string,
  facts: FactItem[],
  prd: PRDData,
  specRaw: string | null,
  nfrMarkdown: string,
): string {
  const sections: string[] = [];

  // Header
  sections.push(`# Implementation Instructions: ${theme}\n`);
  sections.push(`> Generated by DeepForm requirements interview. Use this as the starting point for implementation.\n`);

  // Product intent
  if (prd.problemDefinition) {
    sections.push(`## プロダクトの目的 (Product Intent)\n\n${prd.problemDefinition}\n`);
  }

  // Target user
  if (prd.targetUser) {
    sections.push(`## 対象ユーザー (Target User)\n\n${prd.targetUser}\n`);
  }

  // Current pain / workflow
  const pains = (facts || []).filter((f) => f.type === "pain");
  const workarounds = (facts || []).filter((f) => f.type === "workaround");
  if (pains.length > 0 || workarounds.length > 0) {
    let painSection = "## 現在の課題とワークアラウンド (Current Pain & Workarounds)\n\n";
    if (pains.length > 0) {
      painSection += "### 課題\n";
      painSection += pains.map((p) => `- ${p.content}${p.severity === "high" ? " [重要]" : ""}`).join("\n");
      painSection += "\n\n";
    }
    if (workarounds.length > 0) {
      painSection += "### 現在のワークアラウンド\n";
      painSection += workarounds.map((w) => `- ${w.content}`).join("\n");
      painSection += "\n";
    }
    sections.push(painSection);
  }

  // Scope: features with acceptance criteria
  if (prd.coreFeatures?.length) {
    let scopeSection = "## スコープ (Scope)\n\n";
    for (const feature of prd.coreFeatures) {
      scopeSection += `### ${feature.name} [${feature.priority}]\n`;
      scopeSection += `${feature.description}\n\n`;
      if (feature.acceptanceCriteria?.length) {
        scopeSection += "**受け入れ基準:**\n";
        scopeSection += feature.acceptanceCriteria.map((a) => `- [ ] ${a}`).join("\n");
        scopeSection += "\n\n";
      }
      if (feature.edgeCases?.length) {
        scopeSection += "**エッジケース:**\n";
        scopeSection += feature.edgeCases.map((e) => `- ${e}`).join("\n");
        scopeSection += "\n\n";
      }
    }
    sections.push(scopeSection);
  }

  // Non-goals
  if (prd.nonGoals?.length) {
    sections.push(`## やらないこと (Non-Goals)\n\n${prd.nonGoals.map((n) => `- ${n}`).join("\n")}\n`);
  }

  // Assumptions and open questions
  const unverified = (facts || []).filter((f) => f.severity === "low" || f.type === "fact");
  if (unverified.length > 0) {
    sections.push(
      `## 前提と未検証事項 (Assumptions & Open Questions)\n\n${unverified
        .slice(0, 5)
        .map((f) => `- ${f.content}`)
        .join("\n")}\n`,
    );
  }

  // NFR defaults
  sections.push(nfrMarkdown);
  sections.push("");

  // Spec (if available)
  if (specRaw) {
    sections.push(`## 実装仕様 (Implementation Spec)\n\n${specRaw}\n`);
  }

  // Implementation notes
  sections.push(`## 実装上の注意 (Implementation Notes)

- モックデータ禁止: すべてのデータは実際の DB/API から取得・保存すること
- バックエンドファースト: DB テーブル → API エンドポイント → UI の順で実装
- データ永続化の検証: 作成 → 保存 → リロード → データが残ることを確認
- 未実装機能は UI 上で「未実装」と明示表示
- エラー時はユーザーに分かりやすいメッセージを表示
`);

  return sections.join("\n");
}

// ---------------------------------------------------------------------------
// POST /sessions/:id/claude-code-export — Generate Claude Code prompt
// ---------------------------------------------------------------------------

claudeCodeExportRoutes.post("/sessions/:id/claude-code-export", async (c) => {
  try {
    const result = await getOwnedSession(c);
    if (isResponse(result)) return result;
    const session = result as Session;
    const id = session.id;

    // Load analysis results
    const factsRow = await db
      .selectFrom("analysis_results")
      .select("data")
      .where("session_id", "=", id)
      .where("type", "=", ANALYSIS_TYPE.FACTS)
      .executeTakeFirst();
    const prdRow = await db
      .selectFrom("analysis_results")
      .select("data")
      .where("session_id", "=", id)
      .where("type", "=", ANALYSIS_TYPE.PRD)
      .executeTakeFirst();
    const specRow = await db
      .selectFrom("analysis_results")
      .select("data")
      .where("session_id", "=", id)
      .where("type", "=", ANALYSIS_TYPE.SPEC)
      .executeTakeFirst();

    if (!factsRow || !prdRow) {
      return c.json({ error: "分析パイプラインを先に実行してください（ファクトと PRD が必要です）" }, 400);
    }

    const factsData = JSON.parse(factsRow.data);
    const prdData = JSON.parse(prdRow.data);
    const prd: PRDData = prdData.prd || prdData;
    const facts: FactItem[] = factsData.facts || [];

    let specRaw: string | null = null;
    if (specRow) {
      const specData = JSON.parse(specRow.data);
      specRaw = specData?.spec?.raw || null;
    }

    // Detect NFR context from interview data
    const nfrContext = detectNFRContext(facts, prd);
    const nfrDefaults = getNFRDefaults(nfrContext);
    const nfrMarkdown = formatNFRsAsMarkdown(nfrDefaults);

    // Build prompt
    const prompt = buildClaudeCodePrompt(session.theme, facts, prd, specRaw, nfrMarkdown);

    // Save export as analysis result for history
    await saveAnalysisResult(id, ANALYSIS_TYPE.CLAUDE_CODE_PROMPT, {
      prompt,
      exportedAt: new Date().toISOString(),
      nfrContext,
    });

    return c.json({
      prompt,
      sessionId: id,
      theme: session.theme,
      exportedAt: new Date().toISOString(),
    });
  } catch (e) {
    console.error("Claude Code export error:", e);
    return c.json({ error: "Internal Server Error" }, 500);
  }
});

// ---------------------------------------------------------------------------
// GET /sessions/:id/claude-code-export — Retrieve previously generated prompt
// ---------------------------------------------------------------------------

claudeCodeExportRoutes.get("/sessions/:id/claude-code-export", async (c) => {
  try {
    const result = await getOwnedSession(c);
    if (isResponse(result)) return result;
    const session = result as Session;
    const id = session.id;

    const exportRow = await db
      .selectFrom("analysis_results")
      .select("data")
      .where("session_id", "=", id)
      .where("type", "=", ANALYSIS_TYPE.CLAUDE_CODE_PROMPT)
      .executeTakeFirst();

    if (!exportRow) {
      return c.json({ error: "Claude Code プロンプトがまだ生成されていません" }, 404);
    }

    const exportData = JSON.parse(exportRow.data);
    return c.json({
      prompt: exportData.prompt,
      sessionId: id,
      theme: session.theme,
      exportedAt: exportData.exportedAt,
    });
  } catch (e) {
    console.error("Claude Code export get error:", e);
    return c.json({ error: "Internal Server Error" }, 500);
  }
});
